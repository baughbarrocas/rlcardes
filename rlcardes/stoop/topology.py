def transition_matrix(device: torch.device | None = None) -> torch.Tensor:
    return torch.tensor(TRANSITION_VALUES, dtype=torch.bool, device=device).reshape(45, 45)


def neighbors(index: int) -> tuple[int, ...]:
    if index < 0 or index >= 45:
        raise IndexError(index)
    offset = index * 45
    return tuple(i for i, allowed in enumerate(TRANSITION_VALUES[offset : offset + 45]) if allowed)


def encode(costimulatory: str, itam: int, hinge: str) -> int:
    key = (costimulatory, itam, hinge)
    for node in CONSTRUCT_NODES:
        if (node.costimulatory, node.itam, node.hinge) == key:
            return node.index
    raise ValueError(key)


def decode(index: int) -> ConstructNode:
    if index < 0 or index >= 45:
        raise IndexError(index)
    return CONSTRUCT_NODES[index]


def shortest_refinement(source: int, target: int) -> tuple[int, ...]:
    if source < 0 or source >= 45 or target < 0 or target >= 45:
        raise IndexError((source, target))
    if source == target:
        return (source,)
    queue: list[tuple[int, tuple[int, ...]]] = [(source, (source,))]
    visited = {source}
    while queue:
        current, path = queue.pop(0)
        for adjacent in neighbors(current):
            if adjacent == target:
                return path + (adjacent,)
            if adjacent not in visited:
                visited.add(adjacent)
                queue.append((adjacent, path + (adjacent,)))
    raise RuntimeError((source, target))
